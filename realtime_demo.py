"""
Real-time Embedding Visualization Demo

This script demonstrates real-time visualization of embeddings
as they are generated by the Transformer Encoder.
"""

import jax
import jax.numpy as jnp
import haiku as hk
import numpy as np
import time
from transformer_encoder import encoder_fn, EmbeddingLayer
from visualizer import EmbeddingVisualizer
import matplotlib.pyplot as plt


def demo_realtime_streaming():
    """
    Simulate streaming embeddings and visualize them in real-time.
    """
    print("=" * 60)
    print("Real-time Embedding Visualization Demo")
    print("=" * 60)
    print()

    # Create visualizer
    viz = EmbeddingVisualizer()
    viz.create_realtime_plot(update_interval=100, max_points=200)

    print("Generating embeddings in real-time...")
    print("Close the plot window to stop.")
    print()

    # Generate embeddings with evolving patterns
    embed_dim = 64
    n_steps = 200

    plt.ion()  # Interactive mode on
    plt.show()

    try:
        for step in range(n_steps):
            # Create embedding with time-varying pattern
            t = step / 50.0
            embedding = np.random.randn(embed_dim) * 0.5

            # Add structured components
            embedding[0] = np.sin(t * 2 * np.pi) * 2
            embedding[1] = np.cos(t * 2 * np.pi) * 2
            embedding[2] = np.sin(t * 4 * np.pi) * 1.5

            # Update visualization
            viz.update_realtime(embedding)

            time.sleep(0.05)  # Simulate processing time

            if step % 20 == 0:
                print(f"  Step {step}/{n_steps}")

    except KeyboardInterrupt:
        print("\nVisualization stopped by user")

    plt.ioff()
    print()
    print("✓ Real-time demo completed!")


def demo_encoder_embeddings():
    """
    Visualize embeddings from the actual Transformer Encoder.
    """
    print("=" * 60)
    print("Encoder Embedding Visualization Demo")
    print("=" * 60)
    print()

    # Configure encoder
    config = {
        'vocab_size': 1000,
        'embed_dim': 128,
        'seq_len': 32,
        'batch_size': 50,
        'n_heads': 4,
        'd_k': 32,
        'hidden_dim': 512,
    }

    print("1. Initializing Transformer Encoder...")
    encoder_transformed = hk.transform(lambda x: encoder_fn(x, config))
    rng = jax.random.PRNGKey(42)
    dummy_input = jnp.zeros((config['batch_size'], config['seq_len']), dtype=jnp.int32)
    params = encoder_transformed.init(rng, dummy_input)
    print("   ✓ Encoder initialized")
    print()

    # Generate sample inputs representing different "categories"
    print("2. Generating sample inputs (3 categories)...")
    n_per_category = config['batch_size'] // 3

    # Category A: Low token IDs (0-300)
    category_a = jax.random.randint(
        jax.random.PRNGKey(0),
        (n_per_category, config['seq_len']),
        0, 300
    )

    # Category B: Mid token IDs (300-700)
    category_b = jax.random.randint(
        jax.random.PRNGKey(1),
        (n_per_category, config['seq_len']),
        300, 700
    )

    # Category C: High token IDs (700-1000)
    category_c = jax.random.randint(
        jax.random.PRNGKey(2),
        (n_per_category, config['seq_len']),
        700, 1000
    )

    all_inputs = jnp.concatenate([category_a, category_b, category_c], axis=0)
    print(f"   ✓ Created {len(all_inputs)} samples across 3 categories")
    print()

    # Get encoder outputs
    print("3. Processing inputs through encoder...")
    outputs = encoder_transformed.apply(params, None, all_inputs)
    print(f"   ✓ Output shape: {outputs.shape}")
    print()

    # Average pooling over sequence length to get sentence embeddings
    sentence_embeddings = jnp.mean(outputs, axis=1)
    print(f"4. Sentence embeddings shape: {sentence_embeddings.shape}")
    print()

    # Create labels and colors
    labels = ['A'] * n_per_category + ['B'] * n_per_category + ['C'] * n_per_category
    colors = np.array([0] * n_per_category + [1] * n_per_category + [2] * n_per_category)

    # Visualize
    viz = EmbeddingVisualizer()

    print("5. Visualizing encoder outputs in 2D...")
    viz.visualize_embeddings_2d(
        np.array(sentence_embeddings),
        method='pca',
        colors=colors,
        title='Encoder Output Embeddings (3 Token Categories)',
        save_path='outputs/encoder_embeddings_2d.png'
    )

    print("6. Visualizing encoder outputs in 3D...")
    viz.visualize_embeddings_3d(
        np.array(sentence_embeddings),
        method='pca',
        colors=colors,
        title='Encoder Output Embeddings (3 Token Categories)',
        save_path='outputs/encoder_embeddings_3d.png'
    )

    print()
    print("✓ Encoder embedding visualization completed!")


