def demo_attention_visualization():
    """
    Generate and visualize attention patterns from the encoder.
    """
    print("=" * 60)
    print("Attention Pattern Visualization")
    print("=" * 60)
    print()

    # For this demo, we'll simulate attention patterns
    # In a real implementation, you would extract actual attention weights
    # from the encoder's multi-head attention layer

    viz = EmbeddingVisualizer()

    # Simulate different attention patterns
    seq_len = 12
    tokens = ["The", "cat", "sat", "on", "the", "mat", "and", "looked", "at", "the", "bird", "."]

    print("1. Simulating focused attention pattern...")
    # Diagonal attention (tokens attending to themselves)
    attention_focused = np.eye(seq_len) * 0.7 + np.random.rand(seq_len, seq_len) * 0.3
    attention_focused = attention_focused / attention_focused.sum(axis=-1, keepdims=True)

    viz.visualize_attention_patterns(
        attention_focused,
        tokens=tokens,
        title='Focused Attention Pattern',
        save_path='outputs/attention_focused.png'
    )

    print("2. Simulating distributed attention pattern...")
    # More distributed attention
    attention_distributed = np.random.rand(seq_len, seq_len)
    attention_distributed = attention_distributed / attention_distributed.sum(axis=-1, keepdims=True)

    viz.visualize_attention_patterns(
        attention_distributed,
        tokens=tokens,
        title='Distributed Attention Pattern',
        save_path='outputs/attention_distributed.png'
    )

    print("3. Simulating local attention pattern...")
    # Local attention (attending to nearby tokens)
    attention_local = np.zeros((seq_len, seq_len))
    for i in range(seq_len):
        for j in range(max(0, i-2), min(seq_len, i+3)):
            attention_local[i, j] = 1.0
    attention_local = attention_local / attention_local.sum(axis=-1, keepdims=True)

    viz.visualize_attention_patterns(
        attention_local,
        tokens=tokens,
        title='Local Attention Pattern',
        save_path='outputs/attention_local.png'
    )

    print()
    print("✓ Attention visualization completed!")


def demo_embedding_comparison():
    """
    Compare embeddings before and after encoder processing.
    """
    print("=" * 60)
    print("Embedding Comparison Demo")
    print("=" * 60)
    print()

    # Configure encoder
    config = {
        'vocab_size': 500,
        'embed_dim': 64,
        'seq_len': 16,
        'batch_size': 30,
        'n_heads': 4,
        'd_k': 16,
        'hidden_dim': 256,
    }

    print("1. Initializing encoder...")
    encoder_transformed = hk.transform(lambda x: encoder_fn(x, config))
    rng = jax.random.PRNGKey(42)
    dummy_input = jnp.zeros((config['batch_size'], config['seq_len']), dtype=jnp.int32)
    params = encoder_transformed.init(rng, dummy_input)

    # Also initialize just the embedding layer
    def embedding_only_fn(x):
        layer = EmbeddingLayer(
            embed_dim=config['embed_dim'],
            vocab_size=config['vocab_size'],
            seq_len=config['seq_len']
        )
        return layer(x)

    embedding_transformed = hk.transform(embedding_only_fn)
    embedding_params = embedding_transformed.init(rng, dummy_input)
    print("   ✓ Models initialized")
    print()

    # Generate sample input
    print("2. Generating sample input...")
    sample_input = jax.random.randint(
        jax.random.PRNGKey(0),
        (config['batch_size'], config['seq_len']),
        0, config['vocab_size']
    )

    # Get embeddings before and after encoder
    raw_embeddings = embedding_transformed.apply(embedding_params, None, sample_input)
    encoder_outputs = encoder_transformed.apply(params, None, sample_input)

    # Average pool over sequence
    raw_sentence_emb = jnp.mean(raw_embeddings, axis=1)
    encoded_sentence_emb = jnp.mean(encoder_outputs, axis=1)

    print(f"   Raw embeddings shape: {raw_sentence_emb.shape}")
    print(f"   Encoded embeddings shape: {encoded_sentence_emb.shape}")
    print()

    # Compare
    print("3. Comparing embeddings...")
    viz = EmbeddingVisualizer()

    viz.compare_embeddings(
        {
            'Raw Embeddings': np.array(raw_sentence_emb),
            'After Encoder': np.array(encoded_sentence_emb),
        },
        method='pca',
        save_path='outputs/embedding_comparison.png'
    )

    print()
    print("✓ Comparison completed!")


